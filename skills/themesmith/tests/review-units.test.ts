import { afterEach, beforeEach, expect, test } from 'bun:test'
import { spawnSync } from 'node:child_process'
import { cpSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { removeDir } from './helpers.ts'

const SKILL_DIR = resolve(import.meta.dir, '..')
let repo: string

function git(...args: string[]) {
  return spawnSync('git', args, { cwd: repo, encoding: 'utf8' }).stdout.trim()
}

function write(file: string, content: string) {
  mkdirSync(join(repo, dirname(file)), { recursive: true })
  writeFileSync(join(repo, file), content)
}

function units() {
  const r = spawnSync('bun', [join(SKILL_DIR, 'scripts/review-units.ts'), '--base', 'main'], { cwd: repo, encoding: 'utf8' })
  return JSON.parse(r.stdout) as {
    units: { kind: string; name: string; files: string[]; changedLines: Record<string, [number, number][]> }[]
    alreadyReviewed: string[]
    skipped: { file: string; reason: string }[]
  }
}

beforeEach(() => {
  repo = mkdtempSync(join(tmpdir(), 'themesmith-units-'))
  git('init', '-q', '-b', 'main')
  git('config', 'user.email', 'test@example.com')
  git('config', 'user.name', 'Test')
  write('sections/hero.liquid', "<div>\n{% render 'hero-image' %}\n{% render 'price' %}\n</div>\n")
  write('snippets/hero-image.liquid', '<img>\n')
  write('snippets/price.liquid', '<span>$1</span>\n')
  write('snippets/footer-links.liquid', '<a>1</a>\n')
  write('apps/search/App.tsx', 'export {}\n')
  write('apps/entries/search.tsx', 'export {}\n')
  write('snippets/vite-tag.liquid', 'built\n')
  write('templates/index.json', '{}\n')
  git('add', '-A')
  git('commit', '-qm', 'init')
  git('checkout', '-qb', 'change')
  mkdirSync(join(repo, '.agents'), { recursive: true })
  write('.agents/themesmith.json', JSON.stringify({ store: 'example.myshopify.com', mode: 'github', generated: ['snippets/vite-tag.liquid'] }))
})

afterEach(() => removeDir(repo))

test('groups a section with the changed snippets it renders, and leaves others as their own units', () => {
  write('sections/hero.liquid', "<div class=\"x\">\n{% render 'hero-image' %}\n{% render 'price' %}\n</div>\n")
  write('snippets/hero-image.liquid', '<img alt="">\n')
  write('snippets/footer-links.liquid', '<a>2</a>\n')
  const { units: u } = units()
  expect(u.map((x) => [x.kind, x.name, x.files])).toEqual([
    ['section', 'hero', ['sections/hero.liquid', 'snippets/hero-image.liquid']],
    ['snippet', 'footer-links', ['snippets/footer-links.liquid']],
  ])
})

test('reports only the changed line ranges', () => {
  write('sections/hero.liquid', "<div class=\"x\">\n{% render 'hero-image' %}\n{% render 'price' %}\n</div>\n")
  expect(units().units[0].changedLines).toEqual({ 'sections/hero.liquid': [[1, 1]] })
})

test('treats a new file as changed from top to bottom', () => {
  write('snippets/badge.liquid', '<b>\nnew\n</b>\n')
  expect(units().units[0].changedLines).toEqual({ 'snippets/badge.liquid': [[1, 4]] })
})

test('puts an entry file in the same unit as its component folder', () => {
  write('apps/search/App.tsx', 'export const a = 1\n')
  write('apps/entries/search.tsx', 'export const b = 1\n')
  expect(units().units.map((x) => [x.kind, x.name, x.files.sort()])).toEqual([
    ['component', 'apps/search', ['apps/entries/search.tsx', 'apps/search/App.tsx']],
  ])
})

test('skips build output and files the review does not cover', () => {
  write('snippets/vite-tag.liquid', 'dev\n')
  write('templates/index.json', '{"a":1}\n')
  const { units: u, skipped } = units()
  expect(u).toEqual([])
  expect(skipped.filter((s) => !s.file.startsWith('.agents/'))).toEqual([
    { file: 'snippets/vite-tag.liquid', reason: 'generated by the build' },
    { file: 'templates/index.json', reason: 'not theme source the review covers' },
  ])
})

test('skips page builder files, which are changed in the builder app', () => {
  write('snippets/reploChunk.abc.0.liquid', '<div>new</div>\n')
  const { units: u, skipped } = units()
  expect(u).toEqual([])
  expect(skipped.filter((s) => !s.file.startsWith('.agents/'))).toEqual([
    { file: 'snippets/reploChunk.abc.0.liquid', reason: 'made by Replo; change it in Replo' },
  ])
})

test('after a review round, lists only the units changed since, still with the whole change\'s lines', () => {
  write('sections/hero.liquid', "<div class=\"x\">\n{% render 'hero-image' %}\n{% render 'price' %}\n</div>\n")
  write('snippets/footer-links.liquid', '<a>2</a>\n')
  spawnSync('bun', [join(SKILL_DIR, 'scripts/review-units.ts'), '--base', 'main', '--done'], { cwd: repo, encoding: 'utf8' })
  expect(units()).toMatchObject({ units: [], alreadyReviewed: ['hero', 'footer-links'] })

  write('sections/hero.liquid', "<div class=\"x\">\n{% render 'hero-image' %}\n{% render 'price' %}\n</div>\n<p>More</p>\n")
  const next = units()
  expect(next.units.map((u) => [u.name, u.changedLines['sections/hero.liquid']])).toEqual([['hero', [[1, 1], [5, 5]]]])
  expect(next).toMatchObject({ alreadyReviewed: ['footer-links'] })
})

test('finds the base branch of a repository whose default branch is master, with no origin/HEAD', () => {
  git('branch', '-m', 'main', 'master')
  write('snippets/footer-links.liquid', '<a>2</a>\n')
  git('add', '-A')
  git('commit', '-qm', 'saved work')
  const r = spawnSync('bun', [join(SKILL_DIR, 'scripts/review-units.ts')], { cwd: repo, encoding: 'utf8' })
  expect(JSON.parse(r.stdout).units.map((u: { name: string }) => u.name)).toEqual(['footer-links'])
})

test('says so, instead of listing nothing, when it cannot find where the work started', () => {
  git('branch', '-m', 'main', 'trunk')
  const r = spawnSync('bun', [join(SKILL_DIR, 'scripts/review-units.ts')], { cwd: repo, encoding: 'utf8' })
  expect(r.status).toBe(1)
  expect(JSON.parse(r.stdout).ok).toBe(false)
})

test('an edit made while the review ran is not marked reviewed when the round finishes', () => {
  write('snippets/footer-links.liquid', '<a>2</a>\n')
  expect(units().units.map((u) => u.name)).toEqual(['footer-links'])
  write('snippets/footer-links.liquid', '<a>3</a>\n')
  spawnSync('bun', [join(SKILL_DIR, 'scripts/review-units.ts'), '--base', 'main', '--done'], { cwd: repo, encoding: 'utf8' })
  expect(units().units.map((u) => u.name)).toEqual(['footer-links'])
})
